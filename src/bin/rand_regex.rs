use std::fs;
use std::io::{self, IsTerminal, Read, Write};
use std::path::Path;
use std::process::ExitCode;

use clap::Parser;
use rand::{SeedableRng, distr::Distribution, rngs::StdRng};
use rand_regex::{EncodedString, Regex};
use regex_syntax::ParserBuilder;
use serde::Serialize;

const PROGRAM: &str = "rand-regex";
const VERSION: &str = "rand-regex 0.0.0 (rand_regex 0.19.0)\n";

#[derive(Debug, Parser)]
#[command(
    name = "rand-regex",
    about = "Generate random strings or byte strings matching a Rust regex",
    disable_version_flag = true
)]
struct Cli {
    /// Regex supplied as one argument
    #[arg(value_name = "PATTERN", conflicts_with = "input")]
    pattern: Option<String>,

    /// Read the complete regex from FILE; use - for stdin
    #[arg(short, long, value_name = "FILE")]
    input: Option<String>,

    /// Number of independent samples to generate
    #[arg(short = 'n', long, default_value_t = 1, value_name = "NUMBER")]
    count: usize,

    /// Seed the upstream random distribution reproducibly
    #[arg(long, value_name = "U64")]
    seed: Option<u64>,

    /// Maximum extra repetitions used for *, +, and open upper bounds
    #[arg(long, default_value_t = 20, value_name = "NUMBER")]
    max_repeat: u32,

    /// Give Perl character classes such as \d their ASCII meanings
    #[arg(long, conflicts_with = "bytes")]
    ascii: bool,

    /// Parse a byte regex and print each generated byte string as lowercase hex
    #[arg(long, conflicts_with_all = ["ascii", "jsonl"])]
    bytes: bool,

    /// Print one {"value":...} object per sample
    #[arg(long, conflicts_with = "bytes")]
    jsonl: bool,

    /// Print CLI and dependency versions
    #[arg(short = 'V', long)]
    version: bool,
}

#[derive(Debug)]
struct CliError {
    status: u8,
    message: String,
}

impl CliError {
    fn usage(message: impl Into<String>) -> Self {
        Self {
            status: 2,
            message: message.into(),
        }
    }

    fn processing(message: impl Into<String>) -> Self {
        Self {
            status: 1,
            message: message.into(),
        }
    }
}

#[derive(Serialize)]
struct JsonOutput<'a> {
    value: &'a str,
}

fn read_pattern(cli: &Cli) -> Result<String, CliError> {
    if let Some(pattern) = &cli.pattern {
        return Ok(pattern.clone());
    }

    let bytes = match cli.input.as_deref() {
        Some("-") => {
            let mut bytes = Vec::new();
            io::stdin().read_to_end(&mut bytes).map_err(|error| {
                CliError::processing(format!("cannot read pattern input: {error}"))
            })?;
            bytes
        }
        Some(path) => fs::read(Path::new(path)).map_err(|error| {
            CliError::processing(format!("cannot read pattern input {path:?}: {error}"))
        })?,
        None if !io::stdin().is_terminal() => {
            let mut bytes = Vec::new();
            io::stdin().read_to_end(&mut bytes).map_err(|error| {
                CliError::processing(format!("cannot read pattern input: {error}"))
            })?;
            bytes
        }
        None => {
            return Err(CliError::usage(
                "provide PATTERN, --input FILE, or a pattern on stdin",
            ));
        }
    };

    String::from_utf8(bytes)
        .map_err(|error| CliError::processing(format!("pattern input is not valid UTF-8: {error}")))
}

fn compile(pattern: &str, cli: &Cli) -> Result<Regex, CliError> {
    if cli.bytes || cli.ascii {
        let mut builder = ParserBuilder::new();
        builder.unicode(false);
        if cli.bytes {
            builder.utf8(false);
        }
        let hir = builder
            .build()
            .parse(pattern)
            .map_err(|error| CliError::processing(format!("invalid regex: {error}")))?;
        Regex::with_hir(hir, cli.max_repeat)
            .map_err(|error| CliError::processing(format!("cannot build generator: {error}")))
    } else {
        Regex::compile(pattern, cli.max_repeat)
            .map_err(|error| CliError::processing(format!("cannot build generator: {error}")))
    }
}

fn push_hex(bytes: &[u8], output: &mut Vec<u8>) {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    output.reserve(bytes.len().saturating_mul(2).saturating_add(1));
    for byte in bytes {
        output.push(HEX[usize::from(byte >> 4)]);
        output.push(HEX[usize::from(byte & 0x0f)]);
    }
    output.push(b'\n');
}

fn generate<R: rand::Rng + ?Sized>(
    rng: &mut R,
    generator: &Regex,
    cli: &Cli,
) -> Result<Vec<u8>, CliError> {
    let mut output = Vec::new();
    for _ in 0..cli.count {
        let sample: EncodedString = generator.sample(rng);
        if cli.bytes {
            push_hex(sample.as_bytes(), &mut output);
            continue;
        }

        let value = sample.as_str().map_err(|error| {
            CliError::processing(format!(
                "generated non-UTF-8 bytes ({error}); rerun with --bytes"
            ))
        })?;
        if cli.jsonl {
            serde_json::to_writer(&mut output, &JsonOutput { value }).map_err(|error| {
                CliError::processing(format!("cannot serialize output: {error}"))
            })?;
        } else {
            output.extend_from_slice(value.as_bytes());
        }
        output.push(b'\n');
    }
    Ok(output)
}

fn execute(cli: &Cli) -> Result<Vec<u8>, CliError> {
    if cli.version {
        if cli.pattern.is_some() || cli.input.is_some() {
            return Err(CliError::usage("--version does not accept a pattern"));
        }
        return Ok(VERSION.as_bytes().to_vec());
    }

    let pattern = read_pattern(cli)?;
    let generator = compile(&pattern, cli)?;
    match cli.seed {
        Some(seed) => generate(&mut StdRng::seed_from_u64(seed), &generator, cli),
        None => generate(&mut rand::rng(), &generator, cli),
    }
}

fn write_output<W: Write>(writer: &mut W, output: &[u8]) -> Result<(), CliError> {
    match writer.write_all(output) {
        Ok(()) => Ok(()),
        Err(error) if error.kind() == io::ErrorKind::BrokenPipe => Ok(()),
        Err(error) => Err(CliError::processing(format!(
            "cannot write stdout: {error}"
        ))),
    }
}

fn report(error: CliError) -> ExitCode {
    eprintln!("{PROGRAM}: {}", error.message);
    if error.status == 2 {
        eprintln!("Try '{PROGRAM} --help' for usage.");
    }
    ExitCode::from(error.status)
}

fn main() -> ExitCode {
    let cli = Cli::parse();
    let output = match execute(&cli) {
        Ok(output) => output,
        Err(error) => return report(error),
    };
    match write_output(&mut io::stdout().lock(), &output) {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => report(error),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    struct FailingWriter(io::ErrorKind);

    impl Write for FailingWriter {
        fn write(&mut self, _buffer: &[u8]) -> io::Result<usize> {
            Err(io::Error::from(self.0))
        }

        fn flush(&mut self) -> io::Result<()> {
            Ok(())
        }
    }

    #[test]
    fn hex_output_preserves_every_byte() {
        let mut output = Vec::new();
        push_hex(&[0, 15, 16, 255], &mut output);
        assert_eq!(output, b"000f10ff\n");
    }

    #[test]
    fn broken_pipe_is_success_and_other_write_errors_are_failures() {
        assert!(write_output(&mut FailingWriter(io::ErrorKind::BrokenPipe), b"x").is_ok());
        let error = write_output(&mut FailingWriter(io::ErrorKind::Other), b"x").unwrap_err();
        assert_eq!(error.status, 1);
        assert!(error.message.starts_with("cannot write stdout:"));
    }
}
